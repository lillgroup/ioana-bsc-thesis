#!/usr/bin/env bash
# ============================================================================
# REST2 in explicit water for the five selected conformers
# ----------------------------------------------------------------------------
# For every ligand in $CONF_DIR/*_lowest_energy_conf.sdf this script runs the
# md-tools REST2 workflow end to end:
#
#   1. parameterise  OpenFF sage-2.2.1 + AM1-BCC (ambertools-sqm)  -> build/parameter/
#   2. solvate       explicit TIP3P box + counter-ions             -> build/built.xml
#   3. REST2 scaler  N_STATES Hamiltonians, tau 0..TAU_MAX linear  -> build/REST2/
#   4. build-md      generate run.sh, input/, min/, REST2-run1/
#   5. run           30 ns of replica exchange per state
#
# Every compound is SELF-CONTAINED under $BASE/<name>/ so the runs never share
# state and can be moved or rerun on their own:
#
#   $BASE/<name>/
#     build/         built.xml, built.pdb, built.solute.pdb, parameter/, REST2/
#     input/ min/    shared stage inputs, generated by build-md
#     REST2.config   the protocol this compound runs
#     REST2-run1/    the run directory; run.sh lives here (cd here to run)
#     run.log        stdout/stderr of this compound's REST2-run1/run.sh
#
# SAFETY / CONVENTIONS
#   * build steps are idempotent: a step whose outputs already exist is skipped,
#     so an interrupted script is simply re-run. Remove the output to redo it.
#   * a run whose remd_records/REST2_prod1.out already says "run_status:
#     completed" is skipped. run.sh itself resumes an interrupted run from its
#     checkpoint, so re-running after a crash is safe.
#   * REST2 production = number_of_exchanges * exchange_interval_steps, at the
#     system's auto timestep (2 fs here, no hydrogen mass repartitioning), so
#     NS -> N_EXCHANGES = NS * 1e6 fs / (exchange_interval_steps * timestep_fs).
#
# USAGE
#   ./run_all.sh                 build every compound, then run them
#   ./run_all.sh --build-only    parameterise + build + generate scripts only
#   ./run_all.sh --run-only      launch the runs (build must already exist)
#   ./run_all.sh --status        progress / acceptance table, nothing is run
#   ./run_all.sh --list          print the compound table and exit
#   ./run_all.sh --only 4ibi     restrict to one compound (build or run phase)
#   ./run_all.sh --detach        build, then launch the runs detached (setsid)
#
# ENV KNOBS (all optional)
#   CONF_DIR=/scicore/home/lill0000/popa0002/thesis/bsc-thesis/conformers
#   BASE=/scicore/home/lill0000/popa0002/thesis/REST2-conformers
#   N_REPLICAS=6  TAU_MAX=0.4  NS=30  EXCHANGE_INTERVAL=1000  TIMESTEP_FS=2
#   PARALLEL=1                   compounds to run at once (default: sequentially)
#   GPUS=0,1,2,3,4,5             GPU pool the runs are spread over
#   MPS=0                        set 1 if PARALLEL*N_REPLICAS > number of GPUs
#   WAIT_FOR_GPUS=1              wait until the pool is idle before running
#                                (this is a shared login node: set 0 to force)
#   GPU_POLL=60  GPU_STABLE=2    poll seconds / consecutive idle checks
#   GPU_WAIT_MAX=0               give up waiting after N s (0 = forever)
# ============================================================================
set -uo pipefail

CONF_DIR="${CONF_DIR:-/scicore/home/lill0000/popa0002/thesis/bsc-thesis/conformers}"
BASE="${BASE:-/scicore/home/lill0000/popa0002/thesis/REST2-conformers}"

N_REPLICAS="${N_REPLICAS:-6}"          # 8 replicas gave 0.42-0.45 for folic acid;
TAU_MAX="${TAU_MAX:-0.4}"              # 6 is steeper - check the neighbour
NS="${NS:-30}"                         # acceptance report after the first run.
EXCHANGE_INTERVAL="${EXCHANGE_INTERVAL:-1000}"
TIMESTEP_FS="${TIMESTEP_FS:-2}"        # md-tools "auto": 2 fs without HMR

PARALLEL="${PARALLEL:-1}"
GPUS="${GPUS:-0,1,2,3,4,5}"
MPS="${MPS:-0}"

WAIT_FOR_GPUS="${WAIT_FOR_GPUS:-1}"    # 1 = wait for an idle pool before launching
GPU_POLL="${GPU_POLL:-60}"
GPU_STABLE="${GPU_STABLE:-2}"
GPU_WAIT_MAX="${GPU_WAIT_MAX:-0}"      # seconds; 0 = wait forever

# name : sdf basename : residue name (<=3 chars, names the readable parameter
# copies and, when build-top solvates, build/<RES>.sdf)
COMPOUNDS=(
  "4ibi:4ibi_lowest_energy_conf.sdf:L01"
  "4ibk:4ibk_lowest_energy_conf.sdf:L02"
  "4j7d:4j7d_lowest_energy_conf.sdf:L03"
  "5mwh:5mwh_lowest_energy_conf.sdf:L04"
  "5ov8:5ov8_lowest_energy_conf.sdf:L05"
)

N_EXCHANGES=$(( NS * 1000000 / (EXCHANGE_INTERVAL * TIMESTEP_FS) ))
PROD_STEPS=$(( N_EXCHANGES * EXCHANGE_INTERVAL ))

PHASE=all            # all | build | run
DETACH=0
ONLY=""

# ---------------------------------------------------------------------------
say() { printf '[%s] %s\n' "$(date +%H:%M:%S)" "$*"; }
die() { printf 'run_all.sh: %s\n' "$*" >&2; exit 1; }

activate_env() {
  export MAMBA_ROOT_PREFIX=/scicore/home/lill0000/popa0002/software/md-stack
  # shellcheck disable=SC1091
  eval "$(/scicore/home/lill0000/popa0002/software/md-stack/bin/micromamba shell hook -s bash)"
  micromamba activate openmm-env || die "could not activate openmm-env"
  export MD_DATA="${MD_DATA:-/scicore/home/lill0000/popa0002/md-data}"
  command -v md-openmm >/dev/null || die "md-openmm not on PATH"
}

selected() {   # selected <name> ; honours --only
  [ -z "$ONLY" ] || [ "$ONLY" = "$1" ]
}

# --- MPS: needed only when we put more ranks than GPUs  -------------------
setup_mps() {
  export CUDA_MPS_PIPE_DIRECTORY="${CUDA_MPS_PIPE_DIRECTORY:-$HOME/.cache/mps/pipe}"
  export CUDA_MPS_LOG_DIRECTORY="${CUDA_MPS_LOG_DIRECTORY:-$HOME/.cache/mps/log}"
  mkdir -p "$CUDA_MPS_PIPE_DIRECTORY" "$CUDA_MPS_LOG_DIRECTORY"
  if pgrep -x nvidia-cuda-mps-control >/dev/null; then
    say "MPS: control daemon already running"
  else
    CUDA_VISIBLE_DEVICES="$GPUS" nvidia-cuda-mps-control -d || die "could not start MPS"
    say "MPS: started on GPUs $GPUS"
  fi
}

# --- GPU availability -----------------------------------------------------
# A GPU counts as free at <10 % util and <3 GiB used, the same test the earlier
# REST2 watcher used. This is a shared login node: another user's 88 GiB/GPU job
# is the normal case, not the exception.
gpu_stats() {       # gpu_stats <index> -> "util mem"; empty on error
  nvidia-smi -i "$1" --query-gpu=utilization.gpu,memory.used \
    --format=csv,noheader,nounits 2>/dev/null | tr -d ','
}
gpu_is_free() {
  local s u m
  s=$(gpu_stats "$1") || return 1
  read -r u m <<<"$s"
  [ "${u:-100}" -lt 10 ] && [ "${m:-99999}" -lt 3000 ]
}
gpu_report() {
  local g s u m b=0
  for g in ${GPUS//,/ }; do
    s=$(gpu_stats "$g"); read -r u m <<<"$s"
    printf '    GPU %-2s util=%-4s%% mem=%-7s MiB  %s\n' "$g" "${u:--}" "${m:--}" \
      "$(gpu_is_free "$g" && echo free || echo BUSY)"
    gpu_is_free "$g" && b=$((b + 1))
  done
  say "GPUs in pool: $GPUS  ($b free)"
}
wait_for_gpus() {
  [ "$WAIT_FOR_GPUS" = 1 ] || { say "WAIT_FOR_GPUS=0 - launching without waiting"; return 0; }
  local start streak=0 now g ok
  start=$(date +%s)
  say "waiting for GPUs $GPUS to be idle ($GPU_STABLE consecutive checks, ${GPU_POLL}s apart; GPU_WAIT_MAX=$GPU_WAIT_MAX)"
  while :; do
    ok=1
    for g in ${GPUS//,/ }; do gpu_is_free "$g" || { ok=0; break; }; done
    if [ "$ok" = 1 ]; then
      streak=$((streak + 1)); say "    free check $streak/$GPU_STABLE"
      [ "$streak" -ge "$GPU_STABLE" ] && { say "GPUs idle - launching"; return 0; }
    else
      [ "$streak" -ne 0 ] && say "    GPUs busy again - resetting"
      streak=0
    fi
    now=$(date +%s)
    if [ "$GPU_WAIT_MAX" -gt 0 ] && [ $(( now - start )) -ge "$GPU_WAIT_MAX" ]; then
      say "GPU_WAIT_MAX=$GPU_WAIT_MAX reached - launching anyway"; return 0
    fi
    sleep "$GPU_POLL"
  done
}

# ---------------------------------------------------------------------------
write_configs() {   # write_configs <root> <build> <name>
  local root="$1" build="$2" name="$3"
  mkdir -p "$build/parameter"

  cat >"$build/parameterize.config" <<EOF
solute:
  kind: ligand
  aliases: [$name]
EOF

  cat >"$build/build-top.config" <<EOF
solute:
  kind: ligand
  parameters: ./parameter
EOF

  cat >"$build/scaler.config" <<EOF
method: REST2
schedule:
  kind: linear
  n_states: $N_REPLICAS
  tau_min: 0.0
  tau_max: $TAU_MAX
EOF

  cat >"$root/REST2.config" <<EOF
protocol: REST2
solvent: explicit

rest2:
  number_of_replicas: $N_REPLICAS
  tau_max: $TAU_MAX
  exchange_interval_steps: $EXCHANGE_INTERVAL
  number_of_exchanges: $N_EXCHANGES
  equilibration_steps: 50000

stages:
  minimization_iterations: 5000
  restrained_nvt_steps: 50000
  restrained_npt_steps: 50000
  unrestrained_npt_steps: 100000

reporting:
  crd_printout_solute: 1000
  crd_printout_whole: 50000
  info_printout: 5000
  checkpoint_printout: 50000
EOF
}

# ---------------------------------------------------------------------------
build_one() {       # build_one <name> <sdf> <res>
  local name="$1" sdf="$2" res="$3"
  local root="$BASE/$name" build="$BASE/$name/build"

  mkdir -p "$root" "$build/parameter"
  [ -f "$CONF_DIR/$sdf" ] || { say "BUILD $name: no input $CONF_DIR/$sdf"; return 1; }
  write_configs "$root" "$build" "$name"
  say "BUILD $name  (resname $res, $N_REPLICAS states, ${NS} ns = $N_EXCHANGES exchanges)"

  # 2. parameterise ---------------------------------------------------------
  if [ -f "$build/parameter/$res.xml" ]; then
    say "  parameterise . already present ($res.xml)"
  else
    cp -f "$CONF_DIR/$sdf" "$build/$name.sdf"     # named copy; resname is $res,
    say "  parameterise . $name.sdf -> parameter/$res.{pdb,xml}"
    md-openmm build-top --parameterize -i "$build/$name.sdf" --resname "$res" \
      --config "$build/parameterize.config" \
      -op "$build/parameter/$res.pdb" -os "$build/parameter/$res.xml" \
      -log "$build/parameterize.log" >"$build/parameterize.out" 2>&1 \
      || { say "  parameterise FAILED (see $build/parameterize.out)"; return 1; }
  fi

  # 3. solvate --------------------------------------------------------------
  if [ -f "$build/built.xml" ]; then
    say "  solvate . already present (built.xml)"
  else
    say "  solvate . parameter/$res.sdf -> built.{xml,pdb}"
    md-openmm build-top -i "$build/parameter/$res.sdf" \
      -os "$build/built.xml" -op "$build/built.pdb" \
      -log "$build/built.log" --config "$build/build-top.config" \
      >"$build/built.out" 2>&1 \
      || { say "  solvate FAILED (see $build/built.out)"; return 1; }
  fi

  # 4. REST2 scaler (runs in build/; writes build/REST2/) -------------------
  if [ -f "$build/REST2/system_state0.xml" ]; then
    say "  scaler . already present (build/REST2/)"
  else
    say "  scaler . built.xml -> build/REST2/system_state{0..$((N_REPLICAS-1))}.xml"
    ( cd "$build" && md-openmm build-top --rest2-scaler \
        -s built.xml -p built.pdb --config scaler.config ) \
      >"$build/scaler.out" 2>&1 \
      || { say "  scaler FAILED (see $build/scaler.out)"; return 1; }
  fi

  # 5. build-md (runs at root; writes input/, min/, REST2-run1/) ------------
  if [ -f "$root/REST2-run1/run.sh" ]; then
    say "  build-md . already present (REST2-run1/run.sh)"
  else
    [ -e "$root/REST2-run1" ] && { say "  build-md: $root/REST2-run1 exists without run.sh - remove it"; return 1; }
    say "  build-md . -> REST2-run1/run.sh"
    ( cd "$root" && md-openmm build-md -odir ./REST2-run1 --config REST2.config ) \
      >"$root/build-md.out" 2>&1 \
      || { say "  build-md FAILED (see $root/build-md.out)"; return 1; }
  fi

  say "BUILD $name ok"
  return 0
}

# ---------------------------------------------------------------------------
run_complete() {    # run_complete <name>
  grep -q '^run_status: completed' \
    "$BASE/$1/REST2-run1/remd_records/REST2_prod1.out" 2>/dev/null
}

run_one() {         # run_one <name> <gpu-list>
  local name="$1" gpus="$2"
  local dir="$BASE/$name/REST2-run1" log="$BASE/$name/run.log"
  [ -f "$dir/run.sh" ] || { say "RUN $name: no $dir/run.sh - build first"; return 1; }
  say "RUN  $name on GPUs $gpus  -> $log"
  (
    cd "$dir" || exit 1
    export CUDA_DEVICE_ORDER=PCI_BUS_ID
    export CUDA_VISIBLE_DEVICES="$gpus"
    ./run.sh
  ) >>"$log" 2>&1
  local rc=$?
  say "RUN  $name exited rc=$rc"
  return $rc
}

run_phase() {
  gpu_report
  wait_for_gpus
  [ "$MPS" = 1 ] && setup_mps

  local gpu_arr per_run slot off slice gpus entry name sdf res
  # shellcheck disable=SC2206
  gpu_arr=( ${GPUS//,/ } )
  [ "${#gpu_arr[@]}" -gt 0 ] || die "GPUS is empty"
  per_run=$(( ${#gpu_arr[@]} / PARALLEL )); [ "$per_run" -lt 1 ] && per_run=1
  if [ $(( PARALLEL * N_REPLICAS )) -gt "${#gpu_arr[@]}" ] && [ "$MPS" != 1 ]; then
    say "WARNING: $((PARALLEL*N_REPLICAS)) ranks over ${#gpu_arr[@]} GPUs without MPS=1 - expect oversubscription"
  fi

  slot=0
  for entry in "${COMPOUNDS[@]}"; do
    IFS=: read -r name sdf res <<<"$entry"
    selected "$name" || continue
    if run_complete "$name"; then say "SKIP $name (already 'run_status: completed')"; continue; fi
    off=$(( (slot % PARALLEL) * per_run ))
    slice=( "${gpu_arr[@]:off:per_run}" )
    gpus=$(IFS=,; echo "${slice[*]}")
    run_one "$name" "$gpus" &
    slot=$((slot + 1))
    (( slot % PARALLEL == 0 )) && wait
  done
  wait

  echo
  say "all requested runs finished - status:"
  status_table
}

# ---------------------------------------------------------------------------
status_table() {
  printf '\n%-6s %-6s %-5s %-7s %-8s %-11s %s\n' \
    NAME PARAM BOX SCALE SCRIPTS RUN ACCEPT
  local entry name sdf res root out rs acc
  for entry in "${COMPOUNDS[@]}"; do
    IFS=: read -r name sdf res <<<"$entry"
    selected "$name" || continue
    root="$BASE/$name"; out="$root/REST2-run1/remd_records/REST2_prod1.out"
    rs="-"
    if [ -f "$out" ]; then
      rs=$(grep -oE 'run_status: .*' "$out" | tail -1 | cut -d' ' -f2-)
      [ -z "$rs" ] && rs=running
    elif [ -f "$root/REST2-run1/run.sh" ]; then
      pgrep -f "md-openmm md-run" >/dev/null && rs=maybe || rs=pending
    fi
    acc=$(grep -oE 'overall +[0-9]+/[0-9]+ +[0-9.]+' "$out" 2>/dev/null | tail -1 | awk '{print $NF}')
    printf '%-6s %-6s %-5s %-7s %-8s %-11s %s\n' "$name" \
      "$([ -f "$root/build/parameter/$res.xml" ] && echo ok || echo -)" \
      "$([ -f "$root/build/built.xml" ] && echo ok || echo -)" \
      "$([ -f "$root/build/REST2/system_state0.xml" ] && echo ok || echo -)" \
      "$([ -f "$root/REST2-run1/run.sh" ] && echo ok || echo -)" \
      "$rs" "${acc:--}"
  done
  printf '\n  ACCEPT is the final overall acceptance ratio; check the per-pair\n'
  printf '  block in each run.output - EVERY neighbouring pair must be >= 0.2.\n'
  printf '  Targets: %s replicas, tau_max %s, %s ns per state.\n\n' "$N_REPLICAS" "$TAU_MAX" "$NS"
}

# ---------------------------------------------------------------------------
usage() { awk 'NR>1 && /^set -uo pipefail/{exit} NR>1{sub(/^# ?/,""); print}' "$0"; exit 0; }

while [ $# -gt 0 ]; do
  case "$1" in
    --build-only) PHASE=build ;;
    --run-only)   PHASE=run ;;
    --status)     activate_env; status_table; exit 0 ;;
    --list)       for e in "${COMPOUNDS[@]}"; do IFS=: read -r n s r <<<"$e"; printf '%-6s %-32s %s\n' "$n" "$s" "$r"; done; exit 0 ;;
    --only)       ONLY="${2:?--only needs a name}"; shift ;;
    --detach)     DETACH=1 ;;
    -h|--help)    usage ;;
    *)            die "unknown argument: $1 (try --help)" ;;
  esac
  shift
done

mkdir -p "$BASE"
activate_env

if [ "$DETACH" = 1 ] && [ "$PHASE" != run ]; then
  [ "$PHASE" = build ] || PHASE=build
  # build in the foreground, then hand the runs to a detached copy of ourselves
  for entry in "${COMPOUNDS[@]}"; do
    IFS=: read -r name sdf res <<<"$entry"; selected "$name" || continue
    build_one "$name" "$sdf" "$res" || say "continuing past $name"
  done
  export DETACH=0
  nohup setsid env N_REPLICAS="$N_REPLICAS" TAU_MAX="$TAU_MAX" NS="$NS" \
      EXCHANGE_INTERVAL="$EXCHANGE_INTERVAL" TIMESTEP_FS="$TIMESTEP_FS" \
      PARALLEL="$PARALLEL" GPUS="$GPUS" MPS="$MPS" BASE="$BASE" \
      CONF_DIR="$CONF_DIR" ONLY="$ONLY" \
      WAIT_FOR_GPUS="$WAIT_FOR_GPUS" GPU_POLL="$GPU_POLL" \
      GPU_STABLE="$GPU_STABLE" GPU_WAIT_MAX="$GPU_WAIT_MAX" \
      "$0" --run-only >>"$BASE/run_all.log" 2>&1 &
  say "runs launched detached (pid $!); follow with:  tail -f $BASE/run_all.log"
  exit 0
fi

case "$PHASE" in
  all|build)
    say "base       $BASE"
    say "compounds  $(( ${#COMPOUNDS[@]} )), $N_REPLICAS states, tau_max $TAU_MAX, ${NS} ns/state"
    for entry in "${COMPOUNDS[@]}"; do
      IFS=: read -r name sdf res <<<"$entry"; selected "$name" || continue
      build_one "$name" "$sdf" "$res" || say "continuing past $name"
    done
    ;;
esac

case "$PHASE" in
  all|run)  run_phase ;;
  build)    echo; status_table ;;
esac
